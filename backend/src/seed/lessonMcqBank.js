export function questionsForSeedLesson(body = {}) {
  const banked = lessonMcqBank[body.title];

  if (Array.isArray(banked) && banked.length) {
    return banked;
  }

  if (Array.isArray(body.questions) && body.questions.length) {
    return body.questions;
  }

  if (body.question && Array.isArray(body.options)) {
    return [
      {
        question: body.question,
        options: body.options,
        correct: Number(body.correct || 0)
      }
    ];
  }

  return [];
}
